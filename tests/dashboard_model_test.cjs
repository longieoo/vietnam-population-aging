const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const M=require('../src/dashboard_model.js');
const root=path.resolve(__dirname,'..');
const payload=JSON.parse(fs.readFileSync(path.join(root,'outputs/tables/dashboard_data.json'),'utf8'));
const all=M.sample(payload.rows,2023);
assert.equal(all.length,217);
assert.equal(M.pair(all,'gdp_ppp','age_65_plus').length,197);
assert.equal(M.pair(all,'age_15_64','employment').length,184);
assert.ok(Math.abs(M.correlation(all,'gdp_ppp','age_65_plus',true)-0.721734189116)<1e-10);
assert.ok(Math.abs(M.correlation(all,'age_15_64','employment')-0.080736887344)<1e-10);
const t=M.thresholdSample(payload.crossings,10,new Set(all.map(r=>r.iso3)));
assert.equal(t.counts.observed,45);assert.equal(t.eligible.length,39);
const vn=all.find(r=>r.iso3==='VNM');
assert.ok(Math.abs(vn.aging_index-vn.age_65_plus/vn.age_0_14*100)<1e-10);
assert.equal(M.change({x:null},{x:5},'x'),null);
assert.equal(M.benchmark([{x:null,population:1}],'x').median,null);
assert.equal(M.benchmark([{x:10,population:1},{x:20,population:3}],'x').weighted,17.5);
assert.equal(M.benchmark([{x:10,population:1},{x:20,population:3}],'x').median,15);
assert.equal(M.correlation([{x:1,y:2},{x:1,y:3},{x:1,y:4}],'x','y'),null);
assert.ok(M.csv([{name:'=SUM(A1)',n:-3,missing:null}],['name','n','missing']).includes('"\'=SUM(A1)","-3",""'));
console.log('Dashboard model: samples, correlations, threshold eligibility, nulls, weighting and CSV verified.');
const assertExtra=require('node:assert/strict');
assertExtra.equal(M.scaled(null,1e6),null);
assertExtra.equal(M.scaled(0,1e6),0);
assertExtra.equal(M.scaled(50,0),null);
assertExtra.deepEqual(M.page([1,2,3,4,5],1,2),{rows:[3,4],index:1,count:3,total:5});
assertExtra.deepEqual(M.page([],999),{rows:[],index:0,count:1,total:0});
assertExtra.equal(M.page([1,2],9).index,0);
